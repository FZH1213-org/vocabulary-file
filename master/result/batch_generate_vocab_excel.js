// 词性推断
function getPOS(word, translation) {
  const w = word.toLowerCase();
  const t = translation;

  // 根据中文释义判断
  if (t.includes('的') || t.endsWith('的')) {
    return 'adj.';
  }

  // 根据单词后缀判断
  if (w.endsWith('tion') || w.endsWith('sion') || w.endsWith('ment') ||
      w.endsWith('ness') || w.endsWith('ity') || w.endsWith('ance') ||
      w.endsWith('ence')) {
    return 'n.';
  }
  if (w.endsWith('ly')) {
    return 'adv.';
  }
  if (w.endsWith('ful') || w.endsWith('less') || w.endsWith('ous') ||
      w.endsWith('ive') || w.endsWith('able') || w.endsWith('al')) {
    return 'adj.';
  }
  if (w.endsWith('ize') || w.endsWith('ify') || w.endsWith('ate')) {
    return 'v.';
  }

  // 根据具体词汇判断
  const nounList = ['snow', 'dorm', 'dictionary', 'pest', 'outlet', 'list', 'technology',
                    'screen', 'shirt', 'speech', 'pollution', 'vapour', 'tile', 'shepherd',
                    'compass', 'rain', 'dessert', 'monster', 'lover', 'nutrition', 'expression', 'fatigue', 'standard'];
  const verbList = ['weave', 'scold', 'wipe', 'pass', 'emphasize', 'alleviate', 'foster',
                    'ride', 'clutch', 'insure', 'injure', 'pat', 'tame', 'fold', 'spur', 'astonish'];
  const adjList = ['spectacular', 'fortunate', 'gloomy', 'vicious', 'important', 'favorite', 'anonymous', 'realistic'];
  const advList = ['nevertheless'];

  if (nounList.includes(w)) return 'n.';
  if (verbList.includes(w)) return 'v.';
  if (adjList.includes(w)) return 'adj.';
  if (advList.includes(w)) return 'adv.';

  return 'v./n.';
}

// 批量处理所有文件夹
const resultDir = __dirname;
const folders = fs.readdirSync(resultDir, { withFileTypes: true })
  .filter(item => item.isDirectory() && !item.name.startsWith('.') && item.name !== 'node_modules')
  .map(item => item.name);

console.log(`找到 ${folders.length} 个文件夹\n`);

let processedCount = 0;
let errorCount = 0;

folders.forEach((folderName, index) => {
  const folderPath = path.join(resultDir, folderName);

  // 查找HTML词汇表文件
  const files = fs.readdirSync(folderPath);
  const htmlFiles = files.filter(f => f.endsWith('_词汇表.html'));

  if (htmlFiles.length === 0) {
    return; // 跳过没有词汇表的文件夹
  }

  const htmlFile = htmlFiles[0];
  const htmlPath = path.join(folderPath, htmlFile);

  try {
    // 读取HTML文件
    const htmlContent = fs.readFileSync(htmlPath, 'utf-8');

    // 提取词汇数据
    const match = htmlContent.match(/const vocabularyData=(\[[\s\S]*?\]);/);
    if (!match) {
      console.log(`❌ ${folderName}: 无法提取词汇数据`);
      errorCount++;
      return;
    }

    const vocabularyData = JSON.parse(match[1]);

    // 生成Excel数据
    const excelData = [
      ['词汇', '音标', '词性', '中文']
    ];

    vocabularyData.forEach(v => {
      excelData.push([
        v.word,
        phoneticMap[v.word.toLowerCase()] || '/' + v.word + '/',
        getPOS(v.word, v.translation),
        v.translation
      ]);
    });

    // 创建工作簿和工作表
    const wb = XLSX.utils.book_new();
    const ws = XLSX.utils.aoa_to_sheet(excelData);

    // 设置列宽
    ws['!cols'] = [
      { wch: 15 },  // 词汇
      { wch: 20 },  // 音标
      { wch: 8 },   // 词性
      { wch: 15 }   // 中文
    ];

    // 添加工作表到工作簿
    XLSX.utils.book_append_sheet(wb, ws, '词汇表');

    // 生成Excel文件名
    const baseName = htmlFile.replace('_词汇表.html', '');
    const excelFile = baseName + '.xlsx';
    const excelPath = path.join(folderPath, excelFile);

    // 写入Excel文件
    XLSX.writeFile(wb, excelPath);

    processedCount++;
    if (index < 10) {
      console.log(`✅ ${folderName}: ${vocabularyData.length}个词汇`);
    }

  } catch (error) {
    console.log(`❌ ${folderName}: ${error.message}`);
    errorCount++;
  }
});

console.log(`\n处理完成！`);
console.log(`成功: ${processedCount} 个文件夹`);
console.log(`失败: ${errorCount} 个文件夹`);